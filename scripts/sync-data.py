# Markdown file patterns — (prefix, how_many_recent_to_copy, min_bytes)
# min_bytes: skip files smaller than this — defense against pipeline LLM-fail
#   producing ~50B stubs that pollute RSS feeds + report pages downstream.
#   Threshold 200B mirrors push-data-to-web.py's MD_PATTERNS guard.
#   Without this, sync-data.py runs first in the CI SSH chain and overwrites
#   hand-backfilled larger files with the still-broken upstream stub
#   (observed 2026-04-30 daily sync clobbering my 6243B restore back to 57B).
MARKDOWN_PATTERNS = [
    ("_ai_social_",            30,   0),   # daily AI social intel
    ("_vla_social_",           30,   0),   # daily VLA social intel
    ("_biweekly_",             12, 200),   # biweekly reports (covers _biweekly_reflection_ too)
    ("_ai_biweekly_",          12, 200),   # AI app biweekly reports
    ("_ai_daily_pick_",        30,   0),   # dated ai daily pick markdown (if exists)
    ("field-state-",            30,   0),  # field-state mechanical signals
    ("ai-field-state-",        30,   0),   # AI Agent trend signals
    ("calibration-check-",     14,   0),   # calibration check JSONs
    ("_weekly_",               12, 200),   # VLA weekly recon reports
    ("_ai_weekly_",            12, 200),   # AI weekly recon reports
    ("funnel-diagnostic-",     14, 200),   # diagnose-funnel.py output
]

# How many days back to look for markdown files (avoid loading ancient files)
MD_MAX_AGE_DAYS = 90


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def log(msg: str, verbose: bool = False, is_verbose: bool = False):
    if is_verbose and not verbose:
        return
    print(msg, flush=True)


def _validate_json(path: Path):
    def reject_constant(_value):
        raise ValueError("Non-finite JSON number")

    with path.open(encoding="utf-8-sig") as handle:
        json.load(handle, parse_constant=reject_constant)


def _copy_to_stage(src: Path, stage: Path):
    try:
        shutil.copy2(src, stage)
    except PermissionError:
        # Keep elevated writes confined to the same staging file. Never copy
        # over the current destination, and never expose subprocess stderr.
        result = subprocess.run(
            ["sudo", "cp", "-p", str(src), str(stage)],
            capture_output=True, text=True,
        )
        if result.returncode:
            raise PermissionError("sudo copy failed")
        result = subprocess.run(
            ["sudo", "chown", f"{os.getuid()}:{os.getgid()}", str(stage)],
            capture_output=True, text=True,
        )
        if result.returncode:
            raise PermissionError("staging ownership repair failed")


def copy_file(src: Path, dst: Path, dry_run: bool, symlink: bool, verbose: bool):
    """Stage, validate JSON, then atomically replace dst; failures retain old dst."""
    if dry_run:
        action = "SYMLINK" if symlink else "COPY"
        log(f"  [dry-run] {action}: {src.name} → {dst}", verbose)
        return True

    stage = None
    try:
        dst.parent.mkdir(parents=True, exist_ok=True)
        descriptor, name = tempfile.mkstemp(prefix=f".{dst.name}.", suffix=".tmp", dir=dst.parent)
        os.close(descriptor)
        stage = Path(name)
        linked = False
        if symlink:
            if src.suffix.lower() == ".json":
                _validate_json(src)
            if src.resolve() == dst.absolute():
                raise OSError("refusing a self-referential symlink")
            stage.unlink()
            try:
                stage.symlink_to(src.resolve())
                linked = True
            except OSError as error:
                log(f"  WARN: symlink unavailable ({type(error).__name__}), falling back to staged copy")
        if not linked:
            _copy_to_stage(src, stage)
            if src.suffix.lower() == ".json":
                _validate_json(stage)
        os.replace(stage, dst)
        log(f"  {'LINK' if linked else 'COPY'}: {src.name}", is_verbose=True, verbose=verbose)
        return True
    except (OSError, ValueError) as error:
        log(f"  ERROR: could not sync {src.name} ({type(error).__name__}); previous destination retained")
        return False
    finally:
        if stage is not None:
            try:
                stage.unlink(missing_ok=True)
            except OSError:
                pass


def select_recent_md(memory_dir: Path, prefix: str, n: int, max_age_days: int) -> list[Path]:
    """
    Find the N most recent files matching {memory_dir}/{prefix}*.md (or .json).
    Filters by date in filename (YYYY-MM-DD) if present.
    """
    cutoff = (datetime.now() - timedelta(days=max_age_days)).date()
    pattern = str(memory_dir / f"{prefix}*")
    candidates = sorted(glob.glob(pattern), reverse=True)  # newest first (lexicographic)

    selected = []
    for path_str in candidates:
        p = Path(path_str)
        if not p.is_file():
            continue
        # Extract date from filename
        date_match = re.search(r"(\d{4}-\d{2}-\d{2})", p.name)
        if date_match:
            try:
                file_date = datetime.strptime(date_match.group(1), "%Y-%m-%d").date()
                if file_date < cutoff:
                    continue  # too old
            except ValueError:
                pass
        selected.append(p)
        if len(selected) >= n:
            break

    return selected


def write_manifest(data_dir: Path, copied: list[str], dry_run: bool,
                   errors: list[str] | None = None, missing: list[str] | None = None):
    """Atomically record this transfer run; synced_at is not source freshness."""
    manifest = {
        "synced_at": datetime.now().astimezone().isoformat(),
        "files": sorted(copied),
        "errors": sorted(errors or []),
        "missing": sorted(missing or []),
    }
    manifest_path = data_dir / "_manifest.json"
    if dry_run:
        log(f"[dry-run] Manifest planned: {len(copied)} files")
        return True
    stage = None
    try:
        data_dir.mkdir(parents=True, exist_ok=True)
        descriptor, name = tempfile.mkstemp(prefix="._manifest.json.", suffix=".tmp", dir=data_dir)
        stage = Path(name)
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            json.dump(manifest, handle, indent=2, ensure_ascii=False)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(stage, manifest_path)
    except (OSError, ValueError) as error:
        log(f"ERROR: manifest update failed ({type(error).__name__}); previous manifest retained")
        return False
    finally:
        if stage is not None:
            try:
                stage.unlink(missing_ok=True)
            except OSError:
                pass
    log(f"Manifest written: {len(copied)} files")
    return True


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(description="Sync pipeline data to src/data/")
    parser.add_argument("--symlink",  action="store_true", help="Use symlinks instead of copy")
    parser.add_argument("--dry-run",  action="store_true", help="Print actions without executing")
    parser.add_argument("--verbose",  action="store_true", help="Verbose output")
    parser.add_argument("--data-dir", type=Path, default=DATA_DIR, help="Output directory (default: src/data/)")
    args = parser.parse_args()
    data_dir = args.data_dir

    if not MEMORY_DIR.exists():
        log(f"ERROR: MEMORY_DIR does not exist: {MEMORY_DIR}")
        log("Run with sudo, or check the path.")
        sys.exit(1)

    if not args.dry_run:
        data_dir.mkdir(parents=True, exist_ok=True)
    log(f"Syncing {MEMORY_DIR} → {data_dir}")
    if args.dry_run:
        log("[DRY RUN MODE — no files will be written]")

    copied: list[str] = []
    errors: list[str] = []
    missing: list[str] = []

    # ── 1. JSON files ──────────────────────────────────────────────────────
    log("\nJSON files:")
    for filename in JSON_FILES:
        src = MEMORY_DIR / filename
        dst = data_dir / filename
        if not src.exists():
            missing.append(filename)
            log(f"  SKIP (not found): {filename}", is_verbose=True, verbose=args.verbose)
            continue
        ok = copy_file(src, dst, args.dry_run, args.symlink, args.verbose)
        if ok:
            copied.append(filename)
        else:
            errors.append(filename)

    # ── 2. Markdown / dated files ──────────────────────────────────────────
    log("\nMarkdown / dated files:")
    skipped_thin: list[tuple[str, int, int]] = []
    for prefix, n, min_bytes in MARKDOWN_PATTERNS:
        files = select_recent_md(MEMORY_DIR, prefix, n, MD_MAX_AGE_DAYS)
        if not files:
            log(f"  SKIP (none found): {prefix}*", is_verbose=True, verbose=args.verbose)
            continue
        log(f"  {prefix}* — {len(files)} file(s)")
        for src in files:
            # Defense layer 1 (collection-time guard): refuse to propagate thin
            # stubs (e.g. _weekly_2026-04-24.md = 57B from a failed LLM run).
            # Mirrors push-data-to-web.py's MD_PATTERNS min_bytes filter.
            try:
                src_size = src.stat().st_size
            except OSError:
                src_size = 0
            if min_bytes > 0 and src_size < min_bytes:
                skipped_thin.append((src.name, src_size, min_bytes))
                continue
            # Defense layer 2 (write-time guard): refuse to shrink an existing
            # healthy markdown (>=min_bytes) down to a thin source. Catches the
            # case where dest was hand-backfilled but the upstream src on the
            # server is still the broken stub.
            dst = data_dir / src.name
            if (
                min_bytes > 0
                and dst.exists()
                and src_size < min_bytes
                and dst.stat().st_size >= min_bytes
            ):
                skipped_thin.append((src.name, src_size, min_bytes))
                continue
            ok = copy_file(src, dst, args.dry_run, args.symlink, args.verbose)
            if ok:
                copied.append(src.name)
            else:
                errors.append(src.name)
    if skipped_thin:
        log(f"\n⚠️  Skipped {len(skipped_thin)} thin markdown stub(s) (likely LLM-fail upstream):")
        for name, size, threshold in skipped_thin:
            log(f"     {name}: {size}B (threshold {threshold}B)")

    # ── 3. VLA daily rating files from tmp/ ───────────────────────────────
    log("\nVLA daily rating files (from memory/tmp/):")
    if MEMORY_TMP_DIR.exists():
        vla_rating_files = select_recent_md(MEMORY_TMP_DIR, "vla-daily-rating-out-", 30, MD_MAX_AGE_DAYS)
        if not vla_rating_files:
            log("  SKIP (none found): vla-daily-rating-out-*", is_verbose=True, verbose=args.verbose)
        else:
            log(f"  vla-daily-rating-out-* — {len(vla_rating_files)} file(s)")
            for src in vla_rating_files:
                dst = data_dir / src.name
                ok = copy_file(src, dst, args.dry_run, args.symlink, args.verbose)
                if ok:
                    copied.append(src.name)
                else:
                    errors.append(src.name)
    else:
        log(f"  SKIP (tmp dir not found): {MEMORY_TMP_DIR}", is_verbose=True, verbose=args.verbose)

    # ── 4. Manifest ────────────────────────────────────────────────────────
    if not write_manifest(data_dir, copied, args.dry_run, errors, missing):
        errors.append("_manifest.json")

    # ── 5. Fix ownership ──────────────────────────────────────────────────
    # When run via sudo, files are root-owned. Fix to admin:admin so
    # non-root processes (CI tar, Astro build) can read them.
    if getattr(os, "getuid", lambda: -1)() == 0 and not args.dry_run:
        import pwd
        try:
            pw = pwd.getpwnam("admin")
            for f in data_dir.iterdir():
                if not f.is_symlink() and f.stat().st_uid == 0:
                    os.chown(f, pw.pw_uid, pw.pw_gid)
        except (KeyError, OSError):
            pass  # non-admin system, skip

    # ── 6. Summary ─────────────────────────────────────────────────────────
    log(f"\nDone: {len(copied)} copied, {len(errors)} errors")
    if errors:
        log(f"Errors: {', '.join(errors)}")
        sys.exit(1)


if __name__ == "__main__":
    main()
